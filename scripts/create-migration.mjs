// Creates a new versioned Prisma migration from changes in prisma/schema.prisma.
//
// `prisma migrate dev` needs a shadow database, which PGlite cannot provide,
// so this script boots a throwaway in-memory PGlite, applies the existing
// migrations to it and writes whatever SQL is still missing to reach the
// current schema.
//
//   npm run db:migration -- <name>
import { execFile } from "node:child_process";
import { existsSync, mkdirSync, readdirSync, writeFileSync } from "node:fs";
import path from "node:path";
import { promisify } from "node:util";
import { PGlite } from "@electric-sql/pglite";
import { PGLiteSocketServer } from "@electric-sql/pglite-socket";

const run = promisify(execFile);
const root = path.resolve(import.meta.dirname, "..");
const migrationsDir = path.join(root, "prisma", "migrations");
const prisma = path.join(root, "node_modules", ".bin", "prisma");

const name = (process.argv[2] ?? "").trim().replace(/[^a-zA-Z0-9_]+/g, "_");
if (!name) {
  console.error("Usage: npm run db:migration -- <name>");
  process.exit(1);
}

const db = await PGlite.create();
const server = new PGLiteSocketServer({ db, port: 0, host: "127.0.0.1", maxConnections: 5 });
await server.start();
const url = `postgresql://postgres:postgres@127.0.0.1:${server.port}/postgres?sslmode=disable`;
const env = { ...process.env, DATABASE_URL: url };

try {
  const existing = existsSync(migrationsDir)
    ? readdirSync(migrationsDir, { withFileTypes: true }).filter((entry) => entry.isDirectory())
    : [];

  if (existing.length > 0) {
    await run(prisma, ["migrate", "deploy"], { cwd: root, env });
  }

  const { stdout } = await run(
    prisma,
    ["migrate", "diff", "--from-url", url, "--to-schema-datamodel", "prisma/schema.prisma", "--script"],
    { cwd: root, env },
  );

  if (stdout.includes("-- This is an empty migration.") || stdout.trim() === "") {
    console.log("Keine Schema-Änderungen gegenüber den vorhandenen Migrationen.");
  } else {
    const timestamp = new Date().toISOString().replace(/\D/g, "").slice(0, 14);
    const dir = path.join(migrationsDir, `${timestamp}_${name}`);
    mkdirSync(dir, { recursive: true });
    writeFileSync(path.join(dir, "migration.sql"), stdout);
    writeFileSync(
      path.join(migrationsDir, "migration_lock.toml"),
      '# Please do not edit this file manually\n# It should be added in your version-control system (e.g., Git)\nprovider = "postgresql"\n',
    );
    console.log(`Migration geschrieben: ${path.relative(root, dir)}/migration.sql`);
  }
} finally {
  await server.stop();
  await db.close();
}
